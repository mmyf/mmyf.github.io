/**
 * Line 轨迹线
 * 提供轨迹线绘制功能
 * @class
 * @extends THING.LineBase
 */
class Line extends THING.LineBase {
  /**
   * 显示/隐藏线段
   * @param {Boolean} visible - 显示/隐藏线段 
   */
  showLines(visible) {}

  /**
   * 显示/隐藏轨迹点
   * @param {Boolean} visible - 显示/隐藏轨迹点
   */
  showPoints(visible) {}
}

export default Line;
